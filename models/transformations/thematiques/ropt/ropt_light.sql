WITH seg AS (
    SELECT
        ropt_id,
        -- Head (ordr=0)
        (array_agg(lc_codeext  ORDER BY ropt_ordr))[1]                  AS sro_nro,
        (array_agg(ti_codeext  ORDER BY ropt_ordr))[1]                  AS tiroir,
        (array_agg(cs_num      ORDER BY ropt_ordr))[1]                  AS cs_num,
        (array_agg(ps_numero   ORDER BY ropt_ordr))[1]                  AS ps_num,
