        (array_agg(cb_codeext  ORDER BY ropt_ordr))[1]                  AS cable,
        (array_agg(cb_capafo   ORDER BY ropt_ordr))[1]                  AS capafo,
        (array_agg(fo_numtub   ORDER BY ropt_ordr))[1]                  AS tube,
        (array_agg(fo_nintub   ORDER BY ropt_ordr))[1]                  AS fo,
        (array_agg(ps_preaff   ORDER BY ropt_ordr))[1]                  AS preaff,
        (array_agg(cb_lgreel   ORDER BY ropt_ordr))[1]                  AS long,
        -- Segments (ordr >= 1)
        (array_agg(COALESCE(bp_codeext, lc_codeext) ORDER BY ropt_ordr))[2:24]  AS dest_candidates,
        (array_agg(COALESCE(bp_codeext, ti_codeext) ORDER BY ropt_ordr))[2:24]  AS bpe,
        (array_agg(ps_fonct    ORDER BY ropt_ordr))[2:24]                       AS foncts,
        (array_agg(cb_codeext  ORDER BY ropt_ordr))[2:24]                       AS cables,
        (array_agg(cb_capafo   ORDER BY ropt_ordr))[2:24]                       AS capafos,
        (array_agg(fo_numtub   ORDER BY ropt_ordr))[2:24]                       AS tubes,
        (array_agg(fo_nintub   ORDER BY ropt_ordr))[2:24]                       AS fos,
        (array_agg(ps_preaff   ORDER BY ropt_ordr))[2:24]                       AS preaffs,
        (array_agg(cb_lgreel   ORDER BY ropt_ordr))[2:24]                       AS longs,
        -- Sort keys (from head)
        (array_agg(ropt_typelog ORDER BY ropt_ordr))[1]                 AS ropt_typelog,
        (array_agg(lc_codeext  ORDER BY ropt_ordr))[1]                  AS sort_lc_codeext,
        (array_agg(ti_codeext  ORDER BY ropt_ordr))[1]                  AS sort_ti_codeext
    FROM {{ ref('ropt_section') }}
    GROUP BY ropt_id
)
